-- SiSFarm - monitoramento do repositório de backups no Supabase.
-- Execute este arquivo uma unica vez no SQL Editor do projeto Supabase.
-- Ele e idempotente: uma nova execucao nao remove registros existentes.

create table if not exists public.backup_repository_checks (
    id bigint generated by default as identity primary key,
    checked_at timestamptz not null default timezone('utc', now()),
    status text not null check (status in ('success', 'warning', 'failure')),
    storage_total_bytes bigint,
    database_backup_bytes bigint,
    files_backup_bytes bigint,
    last_backup_at timestamptz,
    details jsonb not null default '{}'::jsonb
);

create index if not exists backup_repository_checks_checked_at_idx
    on public.backup_repository_checks (checked_at desc);

alter table public.backup_repository_checks enable row level security;

-- Nenhum usuario da aplicacao le ou altera registros tecnicos de monitoramento.
revoke all on table public.backup_repository_checks from anon, authenticated;

-- O backend usa a service_role do Supabase, que ignora RLS para registrar a verificacao.
grant usage, select on sequence public.backup_repository_checks_id_seq to service_role;
grant select, insert on table public.backup_repository_checks to service_role;
